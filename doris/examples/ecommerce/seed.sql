INSERT INTO agg_shop_daily
SELECT
    order_date,
    shop_id,
    category_id,
    SUM(quantity * unit_price - discount_amount),
    SUM(quantity),
    BITMAP_UNION(TO_BITMAP(order_id)),
    HLL_UNION(HLL_HASH(user_id))
FROM fact_order_items
GROUP BY order_date, shop_id, category_id;

