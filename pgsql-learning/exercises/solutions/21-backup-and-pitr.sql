-- Solutions 21 — Backup and PITR
SET search_path = sql_core, public;

-- Q1 — backup / archive GUCs
SELECT name, setting, unit, short_desc
  FROM pg_settings
 WHERE category ILIKE '%wal%archive%'
    OR name IN ('archive_mode','archive_command','archive_timeout',
                'wal_level','max_wal_senders','wal_compression')
 ORDER BY name;

-- Q2 — capture WAL delta around 100 inserts
SELECT pg_current_wal_lsn() AS lsn_before;
DROP TABLE IF EXISTS pit_ex21;
CREATE TABLE pit_ex21 (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, label text);
INSERT INTO pit_ex21 (label)
SELECT 'row-' || g FROM generate_series(1, 100) g;
SELECT pg_current_wal_lsn() AS lsn_after;
-- Bytes of WAL generated by the inserts:
SELECT pg_wal_lsn_diff(
         (SELECT pg_current_wal_lsn()),
         '0/0')::bigint
       AS cumulative_wal_bytes_since_cluster_start;

-- Q3 — force a CHECKPOINT, then read pg_stat_archiver
CHECKPOINT;
SELECT archived_count,
       last_archived_wal,
       last_archived_time,
       failed_count,
       last_failed_wal,
       last_failed_time
  FROM pg_stat_archiver;

