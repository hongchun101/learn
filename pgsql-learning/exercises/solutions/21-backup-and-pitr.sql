-- Q5 — pg_stat_progress_basebackup during an in-progress backup
-- The view is empty unless pg_basebackup is running. To trigger:
--   docker compose -f docker/docker-compose.yml exec primary \
--     pg_basebackup -D /tmp/backup -Ft -z -P -U postgres
-- Then in psql:
SELECT pid, phase, backup_total, backup_streamed,
       tablespaces_total, tablespaces_streamed
  FROM pg_stat_progress_basebackup;

